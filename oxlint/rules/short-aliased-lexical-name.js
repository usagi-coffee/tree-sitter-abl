import {
  callName,
  enclosingRule,
  isRuleDisabled,
  isRuleProperty,
  memberName,
  report,
  rule,
  ruleName,
} from "../helpers.js";

export const shortAliasedLexicalName = rule((context) => {
  const properties = [],
    references = new Map();
  return {
    Property(node) {
      if (isRuleProperty(node)) properties.push(node);
    },
    MemberExpression(node) {
      const name = memberName(node);
      if (!name) return;
      const uses = references.get(name) ?? [];
      uses.push(node);
      references.set(name, uses);
    },
    "Program:exit"() {
      for (const property of properties) {
        const name = ruleName(property),
          match = name.match(/^__(.+)_routine_name$/);
        if (!match || !["token", "token.immediate"].includes(callName(property.value.body)))
          continue;
        const shorter = `__${match[1]}_name`;
        if (
          properties.some((other) => ruleName(other) === shorter) ||
          isRuleDisabled(context, property)
        )
          continue;
        const uses = references.get(name) ?? [];
        if (
          uses.length === 0 ||
          !uses.every((use) => {
            const alias = use.parent;
            return (
              enclosingRule(use) &&
              callName(alias) === "alias" &&
              alias.arguments.length === 2 &&
              alias.arguments[0] === use &&
              memberName(alias.arguments[1]) === "identifier"
            );
          })
        )
          continue;
        report(
          context,
          property,
          "short-aliased-lexical-name",
          `${name} is a private token locally exposed only as identifier; consider the shorter descriptive name ${shorter}. Check cross-file uses, metadata and collisions, preserve the token definition and every alias, then measure generated bytes and compare complete CSTs.`,
        );
      }
    },
  };
}, "Suggest shorter private lexical names while preserving their visible identifier aliases");
